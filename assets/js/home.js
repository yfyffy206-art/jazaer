  function applyLang(code) {
    var t = I18N[code] || I18N.ar;
    document.documentElement.lang = t.lang;
    document.documentElement.dir = t.dir;
    document.title = t.title;
    if (descMeta) descMeta.setAttribute('content', t.desc);
    if (ogTitle) ogTitle.setAttribute('content', t.title);
    if (ogDesc) ogDesc.setAttribute('content', t.desc);

    textNodes.forEach(function (node, i) {
      if (t.texts[i] != null) node.nodeValue = t.texts[i];
    });

    images.forEach(function (img, i) {
      if (img.dataset.baseSrc === undefined) img.dataset.baseSrc = img.getAttribute('src');
      img.setAttribute('src', img.dataset.baseSrc.replace(/-(ar|en)\.jpg$/, '-' + t.img + '.jpg'));
      if (t.alts[i] != null) img.setAttribute('alt', t.alts[i]);
    });

    var ph = PLACEHOLDERS[code] || PLACEHOLDERS.ar;
    var nameField = root.querySelector('[data-testid="input-name"]');
    var phoneField = root.querySelector('[data-testid="input-phone"]');
    var closeBtn = root.querySelector('[data-testid="modal-close-button"]');
    if (nameField) nameField.setAttribute('placeholder', ph.name);
    if (phoneField) phoneField.setAttribute('placeholder', ph.phone);
    if (closeBtn) closeBtn.setAttribute('aria-label', ph.close);

    Object.keys(langButtons).forEach(function (key) {
      if (langButtons[key]) langButtons[key].className = t.langcls[key] || langButtons[key].className;
    });

    try { localStorage.setItem(STORAGE_KEY, code); } catch (e) {}
    if (window.SiteLang) window.SiteLang.set(code);
  }

  Object.keys(langButtons).forEach(function (code) {
    if (langButtons[code]) {
      langButtons[code].addEventListener('click', function () { applyLang(code); });
    }
  });

  var saved = 'ar';
  try {
    var fromUrl = new URLSearchParams(window.location.search).get('lang');
    saved = (fromUrl && I18N[fromUrl]) ? fromUrl : (localStorage.getItem(STORAGE_KEY) || 'ar');
  } catch (e) {}
  applyLang(I18N[saved] ? saved : 'ar');

  var slider = root.querySelector('[data-testid="promo-slider"]');
  if (slider) {
    var slides = Array.prototype.slice.call(slider.querySelectorAll('img'));
    var dots = Array.prototype.slice.call(slider.querySelectorAll('[data-testid^="slider-dot-"]'));
    var current = 0;
    slides.forEach(function (s, i) { if (s.classList.contains('opacity-100')) current = i; });
    var timer = null;

    function show(index) {
      current = index;
      slides.forEach(function (s, i) {
        s.classList.toggle('opacity-100', i === index);
        s.classList.toggle('opacity-0', i !== index);
      });
      dots.forEach(function (d, i) {
        var on = i === index;
        d.classList.toggle('w-6', on);
        d.classList.toggle('w-1.5', !on);
        d.classList.toggle('bg-white', on);
        d.classList.toggle('bg-white/50', !on);
      });
    }

    function start() {
      stop();
      timer = setInterval(function () { show((current + 1) % slides.length); }, 4000);
    }
    function stop() { if (timer) { clearInterval(timer); timer = null; } }

    dots.forEach(function (dot, i) {
      dot.addEventListener('click', function () { show(i); start(); });
    });
    show(current);
    start();
  }

